struct HUFFNODE
{
	HUFFNODE* pPrev;                // 0x00 Previous node in the list sorted by weight
	HUFFNODE* pNext;                // 0x04
	uint32_t nValue;                // 0x08
	uint32_t nWeight;               // 0x0C
	HUFFNODE* pParent;              // 0x10
	HUFFNODE* pChildLo;             // 0x14
};

// Decoding cache, indexed by the next 7 bits of the input
struct HUFFCACHE
{
	uint32_t nGeneration;           // The entry is valid if this matches the generation of the tree
	uint32_t nBits;
	union
	{
		uint32_t nValue;            // nBits <= 7
		HUFFNODE* pNode;            // nBits > 7: node reached after 7 bits
	};
};

struct HUFFTREE
{
	bool bIsCmp0;                   // Compression type 0 adapts the weights on every value
	uint32_t nGeneration;           // Incremented every time the tree changes
	HUFFNODE pNodes[SCOMP_HUFFMAN_NODES];
	HUFFNODE sentinel;              // Head and tail of the list sorted by weight
	uint32_t nNodesUsed;
	HUFFNODE* pItems[SCOMP_HUFFMAN_VALUES];
	HUFFCACHE pCache[SCOMP_HUFFMAN_CACHE_SIZE];
};

struct HUFFOUTPUTSTREAM
{
	uint8_t* pStart;
	uint32_t nBytesLeft;
	uint8_t* pCurrent;
	uint32_t nBitBuffer;
	uint32_t nBitCount;
};

struct HUFFINPUTSTREAM
{
	const uint8_t* pCurrent;
	uint32_t nBitBuffer;
	uint32_t nBitCount;
};


static inline HUFFNODE* SCompHuffmanHead(HUFFTREE* pTree)
{
	return pTree->sentinel.pNext != &pTree->sentinel ? pTree->sentinel.pNext : nullptr;
}

static inline HUFFNODE* SCompHuffmanTail(HUFFTREE* pTree)
{
	return pTree->sentinel.pPrev != &pTree->sentinel ? pTree->sentinel.pPrev : nullptr;
}

static inline HUFFNODE* SCompHuffmanNext(HUFFTREE* pTree, HUFFNODE* pNode)
{
	return pNode->pNext != &pTree->sentinel ? pNode->pNext : nullptr;
}

static inline void SCompHuffmanUnlink(HUFFNODE* pNode)
{
	if (pNode->pPrev)
	{
		pNode->pPrev->pNext = pNode->pNext;
		pNode->pNext->pPrev = pNode->pPrev;
		pNode->pPrev = nullptr;
		pNode->pNext = nullptr;
	}
}

// Inserts the node before pExisting, or at the tail of the list if pExisting is null
static inline void SCompHuffmanInsertBefore(HUFFTREE* pTree, HUFFNODE* pNode, HUFFNODE* pExisting)
{
	SCompHuffmanUnlink(pNode);
	HUFFNODE* pNextNode = pExisting ? pExisting : &pTree->sentinel;
	pNode->pNext = pNextNode;
	pNode->pPrev = pNextNode->pPrev;
	pNextNode->pPrev->pNext = pNode;
	pNextNode->pPrev = pNode;
}

static inline void SCompHuffmanLinkToHead(HUFFTREE* pTree, HUFFNODE* pNode)
{
	SCompHuffmanUnlink(pNode);
	pNode->pPrev = &pTree->sentinel;
	pNode->pNext = pTree->sentinel.pNext;
	pTree->sentinel.pNext->pPrev = pNode;
	pTree->sentinel.pNext = pNode;
}

static inline HUFFNODE* SCompHuffmanNewNode(HUFFTREE* pTree)
{
	return &pTree->pNodes[pTree->nNodesUsed++];
}

// Storm.0x6FFBB310
static void SCompHuffmanInitTree(HUFFTREE* pTree)
{
	for (HUFFNODE& node : pTree->pNodes)
	{
		node.pPrev = nullptr;
		node.pNext = nullptr;
	}
	pTree->sentinel.pPrev = &pTree->sentinel;
	pTree->sentinel.pNext = &pTree->sentinel;
	pTree->nGeneration = 1;
	pTree->nNodesUsed = 0;
}

// Storm.0x6FFBB7B0
static void SCompHuffmanInitDecodingTree(HUFFTREE* pTree)
{
	SCompHuffmanInitTree(pTree);
	for (HUFFCACHE& cache : pTree->pCache)
	{
		cache.nGeneration = 0;
	}
}

// Inserts a node in the list sorted by weight. The node must be linked at the tail of the list.
static void SCompHuffmanInsertByWeight(HUFFTREE* pTree, HUFFNODE* pNode, HUFFNODE* pSearchStart, uint32_t* pMaxWeight)
{
	if (pNode->nWeight >= *pMaxWeight)
	{
		*pMaxWeight = pNode->nWeight;
		return;
	}

	HUFFNODE* pExisting = pSearchStart;
	while (pExisting && pExisting->nWeight < pNode->nWeight)
	{
		pExisting = SCompHuffmanNext(pTree, pExisting);
	}
	SCompHuffmanInsertBefore(pTree, pNode, pExisting);
}

// Storm.0x6FFBB520
static void SCompHuffmanBuildTree(HUFFTREE* pTree, uint32_t nType)
{
	while (HUFFNODE* pNode = SCompHuffmanHead(pTree))
	{
		SCompHuffmanUnlink(pNode);
	}
	memset(pTree->pItems, 0, sizeof(pTree->pItems));

	// Values with a non null weight
	static const uint8_t sgNoWeights[SCOMP_HUFFMAN_VALUES] = {};
	const uint8_t* pWeights = nType < SCOMP_HUFFMAN_TYPES ? sgHuffmanWeightTables[nType] : sgNoWeights;
	uint32_t nMaxWeight = 0;
	for (uint32_t nValue = 0; nValue < 0x100; ++nValue)
	{
		if (pWeights[nValue])
		{
			HUFFNODE* pNode = SCompHuffmanNewNode(pTree);
			SCompHuffmanInsertBefore(pTree, pNode, nullptr);
			pNode->pParent = nullptr;
			pNode->pChildLo = nullptr;
			pTree->pItems[nValue] = pNode;
			pNode->nValue = nValue;
			pNode->nWeight = pWeights[nValue];
			SCompHuffmanInsertByWeight(pTree, pNode, SCompHuffmanHead(pTree), &nMaxWeight);
		}
	}

	// Special values
	for (uint32_t nValue = 0x100; nValue < SCOMP_HUFFMAN_VALUES; ++nValue)
	{
		HUFFNODE* pNode = SCompHuffmanNewNode(pTree);
		SCompHuffmanLinkToHead(pTree, pNode);
		pNode->pParent = nullptr;
		pNode->pChildLo = nullptr;
		pTree->pItems[nValue] = pNode;
		pNode->nValue = nValue;
		pNode->nWeight = 1;
	}

	// Build the tree by joining the nodes with the lowest weight
	for (HUFFNODE* pChildLo = SCompHuffmanHead(pTree); pChildLo; )
	{
		HUFFNODE* pChildHi = SCompHuffmanNext(pTree, pChildLo);
		if (!pChildHi)
		{
			break;
		}

		HUFFNODE* pParent = SCompHuffmanNewNode(pTree);
		SCompHuffmanInsertBefore(pTree, pParent, nullptr);
		pParent->pParent = nullptr;
		pParent->pChildLo = pChildLo;
		pParent->nWeight = pChildHi->nWeight + pChildLo->nWeight;
		pChildLo->pParent = pParent;
		pChildHi->pParent = pParent;
		SCompHuffmanInsertByWeight(pTree, pParent, SCompHuffmanNext(pTree, pChildHi), &nMaxWeight);

		pChildLo = SCompHuffmanNext(pTree, pChildHi);
	}

	pTree->nGeneration = 1;
}

// Storm.0x6FFBBB10
static void SCompHuffmanIncrementWeights(HUFFTREE* pTree, HUFFNODE* pNode)
{
	for (; pNode; pNode = pNode->pParent)
	{
		const uint32_t nWeight = ++pNode->nWeight;

		// Find the last node with a lower weight
		HUFFNODE* pLower = pNode;
		HUFFNODE* pHigher;
		while (true)
		{
			pHigher = SCompHuffmanNext(pTree, pLower);
			if (!pHigher || pHigher->nWeight >= nWeight)
			{
				break;
			}
			pLower = pHigher;
		}

		if (pLower == pNode)
		{
			continue;
		}

		// Swap the nodes in the list and in the tree
		SCompHuffmanInsertBefore(pTree, pLower, pNode);
		SCompHuffmanInsertBefore(pTree, pNode, pHigher);

		HUFFNODE* pLowerParentChildLo = pLower->pParent->pChildLo;
		if (pNode->pParent->pChildLo == pNode)
		{
			pNode->pParent->pChildLo = pLower;
		}
		if (pLowerParentChildLo == pLower)
		{
			pLower->pParent->pChildLo = pNode;
		}

		HUFFNODE* pParent = pNode->pParent;
		pNode->pParent = pLower->pParent;
		pLower->pParent = pParent;
		++pTree->nGeneration;
	}
}

// Storm.0x6FFBB370
// Splits the node with the lowest weight to add a new value to the tree
static void SCompHuffmanInsertNewValue(HUFFTREE* pTree, uint32_t nValue)
{
	HUFFNODE* pLowest = SCompHuffmanHead(pTree);

	HUFFNODE* pCopy = SCompHuffmanNewNode(pTree);
	SCompHuffmanLinkToHead(pTree, pCopy);
	pCopy->pParent = nullptr;
	pCopy->pChildLo = nullptr;
	pCopy->nValue = pLowest->nValue;
	pCopy->nWeight = pLowest->nWeight;
	pCopy->pParent = pLowest;
	pTree->pItems[pCopy->nValue] = pCopy;

	HUFFNODE* pNew = SCompHuffmanNewNode(pTree);
	SCompHuffmanLinkToHead(pTree, pNew);
	pNew->pChildLo = nullptr;
	pNew->nValue = nValue;
	pNew->nWeight = 0;
	pNew->pParent = pLowest;
	pTree->pItems[nValue] = pNew;
	pLowest->pChildLo = pNew;

	SCompHuffmanIncrementWeights(pTree, pNew);
}

// Storm.0x6FFBBF10
static void SCompHuffmanPutBits(HUFFOUTPUTSTREAM* pStream, uint32_t nValue, uint32_t nBits)
{
	pStream->nBitBuffer |= nValue << pStream->nBitCount;
	pStream->nBitCount += nBits;
	while (pStream->nBitCount >= 8)
	{
		if (pStream->nBytesLeft)
		{
			*pStream->pCurrent++ = (uint8_t)pStream->nBitBuffer;
			--pStream->nBytesLeft;
		}
		pStream->nBitBuffer >>= 8;
		pStream->nBitCount -= 8;
	}
}

// Storm.0x6FFBB2C0
static void SCompHuffmanFlush(HUFFOUTPUTSTREAM* pStream)
{
	while (pStream->nBitCount)
	{
		if (pStream->nBytesLeft)
		{
			*pStream->pCurrent++ = (uint8_t)pStream->nBitBuffer;
			--pStream->nBytesLeft;
		}
		pStream->nBitBuffer >>= 8;
		pStream->nBitCount = pStream->nBitCount > 8 ? pStream->nBitCount - 8 : 0;
	}
}

// Storm.0x6FFBBF70
static void SCompHuffmanEncodeNode(HUFFOUTPUTSTREAM* pStream, HUFFNODE* pNode)
{
	uint32_t nCode = 0;
	uint32_t nBits = 0;
	for (HUFFNODE* pParent = pNode->pParent; pParent; pNode = pParent, pParent = pParent->pParent)
	{
		nCode = (nCode << 1) | (pParent->pChildLo != pNode ? 1 : 0);
		++nBits;
	}
	SCompHuffmanPutBits(pStream, nCode, nBits);
}

uint32_t SCompHuffmanCompress(void* pOut, uint32_t nOutSize, const void* pIn, uint32_t nInSize, uint32_t nType)
{
	HUFFOUTPUTSTREAM stream;
	stream.pStart = (uint8_t*)pOut;
	stream.pCurrent = (uint8_t*)pOut;
	stream.nBytesLeft = nOutSize;
	stream.nBitBuffer = 0;
	stream.nBitCount = 0;

	HUFFTREE tree;
	HUFFTREE* pTree = &tree;
	SCompHuffmanInitTree(pTree);
	SCompHuffmanBuildTree(pTree, nType & 0xFF);
	pTree->bIsCmp0 = (nType & 0xFF) == 0;

	SCompHuffmanPutBits(&stream, nType & 0xFF, 8);

	const uint8_t* pInput = (const uint8_t*)pIn;
	for (uint32_t i = 0; i < nInSize; ++i)
	{
		const uint8_t nValue = pInput[i];
		if (HUFFNODE* pNode = pTree->pItems[nValue])
		{
			SCompHuffmanEncodeNode(&stream, pNode);
			if (pTree->bIsCmp0)
			{
				SCompHuffmanIncrementWeights(pTree, pTree->pItems[nValue]);
			}
		}
		else
		{
			SCompHuffmanEncodeNode(&stream, pTree->pItems[SCOMP_HUFFMAN_NEWVALUE]);
			SCompHuffmanPutBits(&stream, nValue, 8);
			SCompHuffmanInsertNewValue(pTree, nValue);
			SCompHuffmanIncrementWeights(pTree, pTree->pItems[nValue]);
		}
	}

	SCompHuffmanEncodeNode(&stream, pTree->pItems[SCOMP_HUFFMAN_END]);
	SCompHuffmanFlush(&stream);
	return (uint32_t)(stream.pCurrent - stream.pStart);
}

// The input is read 16 bits at a time when peeking, and 32 bits at a time when reading single bits
static inline void SCompHuffmanEnsureBits(HUFFINPUTSTREAM* pStream, uint32_t nMinBits)
{
	if (pStream->nBitCount <= nMinBits)
	{
		uint16_t nWord;
		memcpy(&nWord, pStream->pCurrent, sizeof(nWord));
		pStream->nBitBuffer |= (uint32_t)nWord << pStream->nBitCount;
		pStream->nBitCount += 16;
		pStream->pCurrent += sizeof(nWord);
	}
}

static inline void SCompHuffmanSkipBits(HUFFINPUTSTREAM* pStream, uint32_t nBits)
{
	pStream->nBitBuffer >>= nBits;
	pStream->nBitCount -= nBits;
}

// Storm.0x6FFBBAE0
static uint32_t SCompHuffmanGetBit(HUFFINPUTSTREAM* pStream)
{
	const uint32_t nBit = pStream->nBitBuffer & 1;
	pStream->nBitBuffer >>= 1;
	if (--pStream->nBitCount == 0)
	{
		memcpy(&pStream->nBitBuffer, pStream->pCurrent, sizeof(pStream->nBitBuffer));
		pStream->pCurrent += sizeof(pStream->nBitBuffer);
		pStream->nBitCount = 32;
	}
	return nBit;
}

uint32_t SCompHuffmanDecompress(void* pOut, uint32_t nOutSize, const void* pIn)
{
	if (!nOutSize)
	{
		return 0;
	}

	HUFFINPUTSTREAM stream;
	memcpy(&stream.nBitBuffer, pIn, sizeof(stream.nBitBuffer));
	stream.pCurrent = (const uint8_t*)pIn + sizeof(stream.nBitBuffer);
	stream.nBitCount = 32;

	HUFFTREE tree;
	HUFFTREE* pTree = &tree;
	SCompHuffmanInitDecodingTree(pTree);

	SCompHuffmanEnsureBits(&stream, 8);
	const uint32_t nType = stream.nBitBuffer & 0xFF;
	SCompHuffmanSkipBits(&stream, 8);
	SCompHuffmanBuildTree(pTree, nType);
	pTree->bIsCmp0 = nType == 0;

	uint8_t* pOutput = (uint8_t*)pOut;
	uint32_t nBytesLeft = nOutSize;
	while (true)
	{
		SCompHuffmanEnsureBits(&stream, 7);

		const uint32_t nCacheIndex = stream.nBitBuffer & (SCOMP_HUFFMAN_CACHE_SIZE - 1);
		HUFFCACHE* pCache = &pTree->pCache[nCacheIndex];
		const bool bCacheValid = pCache->nGeneration == pTree->nGeneration;

		uint32_t nValue;
		HUFFNODE* pNode;
		if (bCacheValid && pCache->nBits <= 7)
		{
			SCompHuffmanSkipBits(&stream, pCache->nBits);
			nValue = pCache->nValue;
		}
		else
		{
			if (bCacheValid)
			{
				SCompHuffmanSkipBits(&stream, 7);
				pNode = pCache->pNode;
			}
			else
			{
				pNode = SCompHuffmanTail(pTree);
			}

			// Walk the tree up to a leaf
			uint32_t nBits = 0;
			HUFFNODE* pNodeAfter7Bits = nullptr;
			do
			{
				pNode = pNode->pChildLo;
				if (SCompHuffmanGetBit(&stream))
				{
					pNode = pNode->pNext;
				}
				if (++nBits == 7)
				{
					pNodeAfter7Bits = pNode;
				}
			}
			while (pNode->pChildLo);

			if (!bCacheValid)
			{
				if (nBits > 7)
				{
					pCache->nGeneration = pTree->nGeneration;
					pCache->nBits = nBits;
					pCache->pNode = pNodeAfter7Bits;
				}
				else
				{
					const uint32_t nStep = 1 << nBits;
					for (uint32_t i = nCacheIndex & (nStep - 1); i < SCOMP_HUFFMAN_CACHE_SIZE; i += nStep)
					{
						pTree->pCache[i].nGeneration = pTree->nGeneration;
						pTree->pCache[i].nBits = nBits;
						pTree->pCache[i].nValue = pNode->nValue;
					}
				}
			}
			nValue = pNode->nValue;
		}

		if (nValue == SCOMP_HUFFMAN_NEWVALUE)
		{
			SCompHuffmanEnsureBits(&stream, 8);
			nValue = stream.nBitBuffer & 0xFF;
			SCompHuffmanSkipBits(&stream, 8);
			SCompHuffmanInsertNewValue(pTree, nValue);
			if (!pTree->bIsCmp0)
			{
				SCompHuffmanIncrementWeights(pTree, pTree->pItems[nValue]);
			}
		}

		if (nValue == SCOMP_HUFFMAN_END)
		{
			break;
		}

		*pOutput++ = (uint8_t)nValue;
		if (!--nBytesLeft)
		{
			break;
		}

		if (pTree->bIsCmp0)
		{
			SCompHuffmanIncrementWeights(pTree, pTree->pItems[nValue]);
		}
	}

	return (uint32_t)(pOutput - (uint8_t*)pOut);
}
