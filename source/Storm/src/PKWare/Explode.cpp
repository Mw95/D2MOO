#pragma pack(push, 4)
struct TDcmpStruct
{
	uint32_t nUnused0000;               // 0000
	uint32_t nType;                     // 0004 PKWARE_CMP_BINARY or PKWARE_CMP_ASCII
	uint32_t nOutputPos;                // 0008 Position in pOutBuffer
	uint32_t nDictSizeBits;             // 000C
	uint32_t nDictSizeMask;             // 0010
	uint32_t nBitBuffer;                // 0014
	uint32_t nExtraBits;                // 0018 Number of bits in nBitBuffer, above the first 8
	uint32_t nInPos;                    // 001C Position in pInBuffer
	uint32_t nInBytes;                  // 0020 Number of bytes in pInBuffer
	void* pParam;                       // 0024
	PKWAREREADBUF pfnReadBuf;           // 0028
	PKWAREWRITEBUF pfnWriteBuf;         // 002C
	uint8_t pOutBuffer[0x2204];         // 0030 0x0000-0x0FFF: previous data, 0x1000-0x1FFF: new data, 0x2000-0x2203: longest repetition overflow
	uint8_t pInBuffer[PKWARE_IN_BUFFER_SIZE]; // 2234
	uint8_t pDistPosCodes[0x100];       // 2A34
	uint8_t pLengthCodes[0x100];        // 2B34
	uint8_t pAsciiTable2C34[0x100];     // 2C34
	uint8_t pAsciiTable2D34[0x100];     // 2D34
	uint8_t pAsciiTable2E34[0x80];      // 2E34
	uint8_t pAsciiTable2EB4[0x100];     // 2EB4
	uint8_t pChBitsAsc[0x100];          // 2FB4
	uint8_t pDistBits[0x40];            // 30B4
	uint8_t pLenBits[0x10];             // 30F4
	uint8_t pExLenBits[0x10];           // 3104
	uint16_t pLenBase[0x10];            // 3114
};
#pragma pack(pop)

static_assert(offsetof(TDcmpStruct, pInBuffer) == 0x2234, "Size mismatch");
static_assert(sizeof(TDcmpStruct) == PKWARE_EXPLODE_BUFFER_SIZE, "Size mismatch");

// Storm.0x6FFE0570
static void PKWareMemCopy(void* pDest, const void* pSource, uint32_t nSize)
{
	uint8_t* pDest8 = (uint8_t*)pDest;
	const uint8_t* pSource8 = (const uint8_t*)pSource;
	for (uint32_t i = 0; i < nSize; ++i)
	{
		pDest8[i] = pSource8[i];
	}
}

// Storm.0x6FFE0430
static void PKWareGenerateDecodeTable(int32_t nCount, const uint8_t* pBits, const uint8_t* pCodes, uint8_t* pDecodeTable)
{
	for (int32_t i = nCount - 1; i >= 0; --i)
	{
		const uint32_t nStep = 1 << pBits[i];
		for (uint32_t nCode = pCodes[i]; nCode < 0x100; nCode += nStep)
		{
			pDecodeTable[nCode] = (uint8_t)i;
		}
	}
}

// Storm.0x6FFE0470
static void PKWareGenerateAsciiTables(TDcmpStruct* pWork)
{
	const uint16_t* pChCode = &sgExplodeChCodeAsc[0xFF];
	for (uint32_t nChar = 0xFF; pChCode >= sgExplodeChCodeAsc; --pChCode, --nChar)
	{
		uint8_t* pChBits = &pWork->pChBitsAsc[nChar];
		const uint8_t nBits = *pChBits;
		if (nBits <= 8)
		{
			for (uint32_t nCode = *pChCode; nCode < 0x100; nCode += 1 << nBits)
			{
				pWork->pAsciiTable2C34[nCode] = (uint8_t)nChar;
			}
		}
		else if (*pChCode & 0xFF)
		{
			pWork->pAsciiTable2C34[*pChCode & 0xFF] = 0xFF;
			if (*pChCode & 0x3F)
			{
				*pChBits -= 4;
				for (uint32_t nCode = *pChCode >> 4; nCode < 0x100; nCode += 1 << *pChBits)
				{
					pWork->pAsciiTable2D34[nCode] = (uint8_t)nChar;
				}
			}
			else
			{
				*pChBits -= 6;
				for (uint32_t nCode = *pChCode >> 6; nCode < 0x80; nCode += 1 << *pChBits)
				{
					pWork->pAsciiTable2E34[nCode] = (uint8_t)nChar;
				}
			}
		}
		else
		{
			*pChBits -= 8;
			for (uint32_t nCode = *pChCode >> 8; nCode < 0x100; nCode += 1 << *pChBits)
			{
				pWork->pAsciiTable2EB4[nCode] = (uint8_t)nChar;
			}
		}
	}
}

// Storm.0x6FFE03A0
// Removes bits from the bit buffer, loading more data when needed. Returns 1 if there is no more data.
static uint32_t PKWareWasteBits(TDcmpStruct* pWork, uint32_t nBits)
{
	if (nBits <= pWork->nExtraBits)
	{
		pWork->nExtraBits -= nBits;
		pWork->nBitBuffer >>= nBits;
		return 0;
	}

	pWork->nBitBuffer >>= pWork->nExtraBits;
	if (pWork->nInPos == pWork->nInBytes)
	{
		pWork->nInPos = sizeof(pWork->pInBuffer);
		pWork->nInBytes = pWork->pfnReadBuf((char*)pWork->pInBuffer, &pWork->nInPos, pWork->pParam);
		if (!pWork->nInBytes)
		{
			return 1;
		}
		pWork->nInPos = 0;
	}

	pWork->nBitBuffer |= pWork->pInBuffer[pWork->nInPos++] << 8;
	pWork->nBitBuffer >>= nBits - pWork->nExtraBits;
	pWork->nExtraBits = pWork->nExtraBits - nBits + 8;
	return 0;
}

// Storm.0x6FFE0170
// Returns a byte (0x000-0x0FF), a repetition length + 0xFE (0x100-0x304), the end marker (0x305) or an error (0x306)
static uint32_t PKWareDecodeLiteral(TDcmpStruct* pWork)
{
	if (pWork->nBitBuffer & 1)
	{
		// Repetition
		if (PKWareWasteBits(pWork, 1))
		{
			return PKWARE_LITERAL_ERROR;
		}

		uint32_t nLengthCode = pWork->pLengthCodes[pWork->nBitBuffer & 0xFF];
		if (PKWareWasteBits(pWork, pWork->pLenBits[nLengthCode]))
		{
			return PKWARE_LITERAL_ERROR;
		}

		const uint8_t nExtraBits = pWork->pExLenBits[nLengthCode];
		if (nExtraBits)
		{
			const uint32_t nExtraLength = pWork->nBitBuffer & ((1 << nExtraBits) - 1);
			if (PKWareWasteBits(pWork, nExtraBits) && nLengthCode + nExtraLength != 0x10E)
			{
				return PKWARE_LITERAL_ERROR;
			}
			nLengthCode = pWork->pLenBase[nLengthCode] + nExtraLength;
		}
		return nLengthCode + 0x100;
	}

	// Literal byte
	if (PKWareWasteBits(pWork, 1))
	{
		return PKWARE_LITERAL_ERROR;
	}

	if (pWork->nType == PKWARE_CMP_BINARY)
	{
		const uint32_t nByte = pWork->nBitBuffer & 0xFF;
		if (PKWareWasteBits(pWork, 8))
		{
			return PKWARE_LITERAL_ERROR;
		}
		return nByte;
	}

	uint32_t nByte;
	if (pWork->nBitBuffer & 0xFF)
	{
		nByte = pWork->pAsciiTable2C34[pWork->nBitBuffer & 0xFF];
		if (nByte == 0xFF)
		{
			if (pWork->nBitBuffer & 0x3F)
			{
				if (PKWareWasteBits(pWork, 4))
				{
					return PKWARE_LITERAL_ERROR;
				}
				nByte = pWork->pAsciiTable2D34[pWork->nBitBuffer & 0xFF];
			}
			else
			{
				if (PKWareWasteBits(pWork, 6))
				{
					return PKWARE_LITERAL_ERROR;
				}
				nByte = pWork->pAsciiTable2E34[pWork->nBitBuffer & 0x7F];
			}
		}
	}
	else
	{
		if (PKWareWasteBits(pWork, 8))
		{
			return PKWARE_LITERAL_ERROR;
		}
		nByte = pWork->pAsciiTable2EB4[pWork->nBitBuffer & 0xFF];
	}

	return PKWareWasteBits(pWork, pWork->pChBitsAsc[nByte]) ? PKWARE_LITERAL_ERROR : nByte;
}

// Storm.0x6FFE0320
// Returns the backward distance of the repetition, or 0 on error
static uint32_t PKWareDecodeDistance(TDcmpStruct* pWork, uint32_t nRepLength)
{
	const uint32_t nDistPosCode = pWork->pDistPosCodes[pWork->nBitBuffer & 0xFF];
	if (PKWareWasteBits(pWork, pWork->pDistBits[nDistPosCode]))
	{
		return 0;
	}

	uint32_t nDistance;
	if (nRepLength == 2)
	{
		nDistance = (nDistPosCode << 2) | (pWork->nBitBuffer & 3);
		if (PKWareWasteBits(pWork, 2))
		{
			return 0;
		}
	}
	else
	{
		nDistance = (nDistPosCode << pWork->nDictSizeBits) | (pWork->nDictSizeMask & pWork->nBitBuffer);
		if (PKWareWasteBits(pWork, pWork->nDictSizeBits))
		{
			return 0;
		}
	}
	return nDistance + 1;
}

// Storm.0x6FFE0070
static uint32_t PKWareExpand(TDcmpStruct* pWork)
{
	uint32_t nLiteral;
	pWork->nOutputPos = 0x1000;
	while ((nLiteral = PKWareDecodeLiteral(pWork)) < PKWARE_LITERAL_END)
	{
		if (nLiteral < 0x100)
		{
			pWork->pOutBuffer[pWork->nOutputPos++] = (uint8_t)nLiteral;
		}
		else
		{
			uint32_t nRepLength = nLiteral - 0xFE;
			const uint32_t nDistance = PKWareDecodeDistance(pWork, nRepLength);
			if (!nDistance)
			{
				nLiteral = PKWARE_LITERAL_ERROR;
				break;
			}

			uint8_t* pTarget = &pWork->pOutBuffer[pWork->nOutputPos];
			const uint8_t* pSource = pTarget - nDistance;
			pWork->nOutputPos += nRepLength;
			do
			{
				*pTarget++ = *pSource++;
			}
			while (--nRepLength);
		}

		if (pWork->nOutputPos >= 0x2000)
		{
			uint32_t nSize = 0x1000;
			pWork->pfnWriteBuf((char*)&pWork->pOutBuffer[0x1000], &nSize, pWork->pParam);
			PKWareMemCopy(pWork->pOutBuffer, &pWork->pOutBuffer[0x1000], pWork->nOutputPos - 0x1000);
			pWork->nOutputPos -= 0x1000;
		}
	}

	uint32_t nSize = pWork->nOutputPos - 0x1000;
	pWork->pfnWriteBuf((char*)&pWork->pOutBuffer[0x1000], &nSize, pWork->pParam);
	return nLiteral;
}

uint32_t __cdecl PKWareExplode(PKWAREREADBUF pfnReadBuf, PKWAREWRITEBUF pfnWriteBuf, void* pWorkBuffer, void* pParam)
{
	TDcmpStruct* pWork = (TDcmpStruct*)pWorkBuffer;
	pWork->pfnReadBuf = pfnReadBuf;
	pWork->pfnWriteBuf = pfnWriteBuf;
	pWork->pParam = pParam;
	pWork->nInPos = sizeof(pWork->pInBuffer);
	pWork->nInBytes = pWork->pfnReadBuf((char*)pWork->pInBuffer, &pWork->nInPos, pWork->pParam);
	if (pWork->nInBytes <= 4)
	{
		return PKWARE_CMP_BAD_DATA;
	}

	pWork->nType = pWork->pInBuffer[0];
	pWork->nDictSizeBits = pWork->pInBuffer[1];
	pWork->nBitBuffer = pWork->pInBuffer[2];
	pWork->nExtraBits = 0;
	pWork->nInPos = 3;

	if (pWork->nDictSizeBits < 4 || pWork->nDictSizeBits > 6)
	{
		return PKWARE_CMP_INVALID_DICTSIZE;
	}

	pWork->nDictSizeMask = 0xFFFF >> (16 - pWork->nDictSizeBits);

	if (pWork->nType != PKWARE_CMP_BINARY)
	{
		if (pWork->nType != PKWARE_CMP_ASCII)
		{
			return PKWARE_CMP_INVALID_MODE;
		}

		PKWareMemCopy(pWork->pChBitsAsc, sgExplodeChBitsAsc, sizeof(pWork->pChBitsAsc));
		PKWareGenerateAsciiTables(pWork);
	}

	PKWareMemCopy(pWork->pLenBits, sgExplodeLenBits, sizeof(pWork->pLenBits));
	PKWareGenerateDecodeTable(0x10, pWork->pLenBits, sgExplodeLenCode, pWork->pLengthCodes);
	PKWareMemCopy(pWork->pExLenBits, sgExplodeExLenBits, sizeof(pWork->pExLenBits));
	PKWareMemCopy(pWork->pLenBase, sgExplodeLenBase, sizeof(pWork->pLenBase));
	PKWareMemCopy(pWork->pDistBits, sgExplodeDistBits, sizeof(pWork->pDistBits));
	PKWareGenerateDecodeTable(0x40, pWork->pDistBits, sgExplodeDistCode, pWork->pDistPosCodes);

	return PKWareExpand(pWork) != PKWARE_LITERAL_ERROR ? PKWARE_CMP_NO_ERROR : PKWARE_CMP_ABORT;
}
